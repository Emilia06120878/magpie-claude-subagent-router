import { createHash } from "node:crypto";
import { ROLES } from "./config.js";

export function agentName(model) {
  const hash = createHash("sha256").update(model, "utf8").digest("hex").slice(0, 10);
  const slug = model.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "model";
  return `router-${slug.slice(0, 31).replace(/-+$/g, "") || "model"}-${hash}`;
}

export function agentDescription(model, roles) {
  const chosen = roles.map((id) => ROLES[id]);
  const prefix = `Use proactively for matching tasks; prefer over general-purpose. Magpie model ${model}.`;
  if (!chosen.length) {
    return `${prefix} No responsibility preference is assigned; use when this model fits the delegated task. 使用模型 ${model} 的通用子代理，未指定职责倾向。父级 Claude 可单独或并行调用，并自行评审综合结果。`;
  }
  const en = chosen.map((role) => role.en).join(", ");
  const zh = chosen.map((role) => role.zh).join("、");
  const hints = chosen.map((role) => role.descriptionEn.split(/[.!?]/)[0]).join("; ");
  return `${prefix} Responsibilities: ${en} (${hints}). 职责：${zh}。父级 Claude 可单独或并行调用，并自行评审综合结果。`;
}

export function agentDocument(model, roles) {
  const name = agentName(model);
  return `---\nname: ${JSON.stringify(name)}\ndescription: ${JSON.stringify(agentDescription(model, roles))}\nmodel: ${JSON.stringify(model)}\n---\n\n<!-- Generated by magpie-claude-subagent-router. Manual edits are preserved and stop automatic updates. -->\n\nYou are a named Claude Code subagent provided by Magpie. Perform only the task delegated by the parent Claude Code agent. Report concrete findings, changes, verification, and unresolved issues. Do not switch models or create further subagents. When other subagents run in parallel, the parent Claude compares, reviews, and synthesizes their results.\n\n你是由 Magpie 提供的具名 Claude Code 子代理。只执行父级 Claude Code 分配的任务，并报告明确的发现、改动、验证结果和未解决问题。不要切换模型或继续创建子代理；并行结果的比较、评审和综合由父级 Claude 负责。\n`;
}
